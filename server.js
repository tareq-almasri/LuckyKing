handlers.getLeaderboardWithUserData = function (args, context) {
  try {
    var statisticName = args.statisticName || "rankingScore";
    var maxResults = args.maxResultsCount || 50;
    var startPosition =
      args.startPosition !== undefined ? args.startPosition : 0;

    var leaderboard = server.GetLeaderboard({
      StatisticName: statisticName,
      StartPosition: startPosition,
      MaxResultsCount: maxResults,
    });

    var results = [];

    var lb = leaderboard.Leaderboard || [];
    for (var i = 0; i < lb.length; i++) {
      var entry = lb[i];

      // Safely try to read a specific key (PlayerData) instead of all user data
      var cosmetics = {};
      try {
        var userDataResult = server.GetUserReadOnlyData({
          PlayFabId: entry.PlayFabId,
          Keys: ["PlayerData"],
        });
        if (
          userDataResult &&
          userDataResult.Data &&
          userDataResult.Data.PlayerData &&
          userDataResult.Data.PlayerData.Value
        ) {
          cosmetics = {
            PlayerData: { Value: userDataResult.Data.PlayerData.Value },
          };
        }
      } catch (inner) {
        // Don't fail the whole function for one user's data fetch
        log.warn(
          "GetUserReadOnlyData failed for " + entry.PlayFabId + ": " + inner
        );
      }

      results.push({
        PlayFabId: entry.PlayFabId,
        DisplayName: entry.DisplayName || "",
        StatValue: entry.StatValue || 0,
        Position: entry.Position || 0,
        UserData: cosmetics,
      });
    }

    // --- Add caller’s own rank ---
    var playerRank = null;
    var playerId = context.playerId; // use context.playerId (currentPlayerId was undefined)
    if (playerId) {
      try {
        var aroundPlayer = server.GetLeaderboardAroundPlayer({
          PlayFabId: playerId,
          StatisticName: statisticName,
          MaxResultsCount: 1,
        });

        if (
          aroundPlayer &&
          aroundPlayer.Leaderboard &&
          aroundPlayer.Leaderboard.length > 0
        ) {
          var selfEntry = aroundPlayer.Leaderboard[0];
          playerRank = {
            PlayFabId: selfEntry.PlayFabId,
            DisplayName: selfEntry.DisplayName || "",
            StatValue: selfEntry.StatValue || 0,
            Position: selfEntry.Position || 0,
          };
        }
      } catch (inner) {
        log.warn(
          "GetLeaderboardAroundPlayer failed for " + playerId + ": " + inner
        );
      }
    }

    return {
      leaderboard: results,
      playerRank: playerRank,
    };
  } catch (e) {
    // Return a serializable error object so the client can see details
    log.error(
      "getLeaderboardWithUserData error: " + e + "\n" + (e.stack || "")
    );
    return {
      __cloudScriptError: true,
      message: e.message || String(e),
      stack: e.stack || "",
    };
  }
};

