handlers.claimForfeit = function (args, context) {
  var playerId = currentPlayerId;
  if (!args || !args.matchId)
    return { success: false, message: "Missing matchId" };
  var matchId = args.matchId;
  var now = Date.now();

  var match = getMatch(matchId);
  if (!match) return { success: false, message: "Match not found" };

  // must have exactly one submission and it must be by this player
  var submissionIds = Object.keys(match.Submissions || {});
  if (submissionIds.length !== 1)
    return {
      success: false,
      message: "Not eligible for forfeit (not single-submission)",
    };

  if (submissionIds[0] !== playerId)
    return { success: false, message: "You are not the submitter" };

  var ts = match.Submissions[playerId].ts;
  if (now - ts < FORFEIT_TIMEOUT_MS)
    return { success: false, message: "Timeout not reached yet" };

  // Grant partial or full forfeit reward — choose policy
  var winner = playerId;
  var loser =
    (match.Players && match.Players.find((p) => p !== playerId)) || null;
  match.Status = "resolved";
  match.ResolvedAt = now;
  match.Winner = winner;
  match.Loser = loser;
  saveMatch(match);

  try {
    // partial reward example: 75% of normal
    grantRewards(
      winner,
      true,
      true,
      match.IsRanked,
      false,
      match.CampaignLvl || 0,
      { forfeit: true }
    );
  } catch (e) {
    log.error("Forfeit reward failed: " + e);
  }

  server.WriteTitleEvent({
    EventName: "PvP_MatchForfeit",
    Body: { GameId: matchId, Winner: winner, Loser: loser },
  });

  return { success: true, message: "Forfeit processed" };
};

