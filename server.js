handlers.submitMatchResult = function (args, context) {
  var playerId = currentPlayerId;
  if (
    !args ||
    !args.matchId ||
    !args.result
    //|| !args.checksum
  ) {
    return {
      success: false,
      message:
        "Missing arguments result is: " +
        args.result +
        "matchId is: " +
        args.matchId,
    };
  }
  var matchId = args.matchId;
  var result = args.result; // "win" or "lose"
  // var checksum = args.checksum;
  var isRanked = args.isRanked;
  var now = Date.now();

  var match = getMatch(matchId);
  if (!match) {
    // Create a new pending match record when first submission arrives
    match = {
      GameId: matchId,
      CreatedAt: now,
      CampaignLvl: args.campaignLevel,
      Players: args.playerList || [playerId], // optional: client passes list
      Submissions: {},
      IsRanked: isRanked,
      Status: "pending",
      ResolvedAt: null,
      Winner: null,
      Loser: null,
    };
  }
  // Prevent double submission by same player
  if (match.Submissions[playerId]) {
    return { success: false, message: "You already submitted for this match." };
  }

  //match.Submissions[playerId] = { result: result, checksum: checksum, ts: now };
  match.Submissions[playerId] = { result: result, ts: now };

  // Save pending
  saveMatch(match);

  if (args.isPvE && match.Players.length == 1) {
    //grantRewards(playFabId, wonBool, isPvP, isRanked, isCampaign, campaignLvl)
    grantRewards(
      playerId,
      result === "win",
      false,
      false,
      Number(match.CampaignLvl) > 0,
      match.CampaignLvl
    );
    log.debug("pve reward granted");
    return {
      success: true,
      verified: true,
      message:
        "Match verified and rewards granted. is campaign? " + match.CampaignLvl,
    };
  }

  // Write audit event
  server.WritePlayerEvent({
    PlayFabId: playerId,
    EventName: "matchResultSubmitted",
    Body: { matchId: matchId, result: result, ts: now, by: playerId },
    //Body: { matchId: matchId, result: result, checksum: checksum, ts: now, by: playerId }
  });

  // Check if we have two submissions
  var submissionIds = Object.keys(match.Submissions);
  if (submissionIds.length === 2) {
    // Compare
    var entries = submissionIds.map((id) => ({
      id: id,
      ...match.Submissions[id],
    }));
    var a = entries[0];
    var b = entries[1];

    // complementary check
    var complementary =
      a.result !== b.result &&
      ((a.result === "win" && b.result === "lose") ||
        (a.result === "lose" && b.result === "win"));
    //if (a.checksum === b.checksum && complementary){
    if (complementary) {
      // Verified clean match
      var winner = a.result === "win" ? a.id : b.id;
      var loser = a.result === "win" ? b.id : a.id;
      match.Status = "resolved";
      match.ResolvedAt = now;
      match.Winner = winner;
      match.Loser = loser;
      saveMatch(match);

      // grant rewards (call your grantRewards or computeReward)
      // Here we assume grantRewards(playFabId, wonBool, isPvP, isRanked, isCampaign, campaignLvl)
      try {
        grantRewards(
          winner,
          true,
          true,
          match.IsRanked,
          false,
          match.CampaignLvl || 0
        );
        grantRewards(
          loser,
          false,
          true,
          match.IsRanked,
          false,
          match.CampaignLvl || 0
        );
      } catch (e) {
        log.error("Reward failure: " + e);
      }

      server.WriteTitleEvent({
        EventName: "PvP_MatchVerified",
        Body: { GameId: matchId, Winner: winner, Loser: loser },
      });

      return {
        success: true,
        verified: true,
        message: "Match verified and rewards granted.",
        winner: winner,
        loser: loser,
      };
    } else {
      // Checksums differ or non complementary results → suspicious
      match.Status = "suspicious";
      saveMatch(match);

      server.WriteTitleEvent({
        EventName: "PvP_MatchSuspicious",
        Body: { GameId: matchId, Submissions: match.Submissions },
      });

      return {
        success: false,
        suspicious: true,
        message: "Match marked suspicious. Manual review required.",
      };
    }
  }

  // Only one submission so far -> wait for opponent or allow forfeit claim later
  return {
    success: true,
    pending: true,
    message: "Submission recorded, waiting for opponent.",
  };
};

