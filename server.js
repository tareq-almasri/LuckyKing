handlers.processMatchResult = function (args, context) {
    var playerId = currentPlayerId;

    if (!args || !args.result || (args.result !== "win" && args.result !== "lose")) {
        return { success: false, message: "Invalid or missing match result." };
    }

    var mode = args.mode || "pve"; // "pvp" | "pve" | "campaign"
    var isRanked = !!args.isRanked;
    var opponentId = args.opponentId || null;
    var matchId = args.matchId || ("pvp_" + Date.now());

    // === STEP 1: Input validation ===
    if (mode === "pvp" && !opponentId) {
        return { success: false, message: "Missing opponentId for PvP match." };
    }

    // === STEP 2: Log the player's PvP result ===
    if (mode === "pvp") {
        if(!args.isSent){
        server.WritePlayerEvent({
            PlayFabId: playerId,
            EventName: "pvpMatchResult",
            Body: {
                opponentId: opponentId,
                result: args.result,   // "win" or "lose"
                isRanked: isRanked,
                matchId: matchId,
                timestamp: new Date().toISOString()
            }
        });
        }
     var opponentEvents = server.GetPlayerEvents({
        PlayFabId: opponentId,
        StartTime: new Date(Date.now() - 1000 * 60 * 10),
        EventNamespace: "custom",
        EventName: "pvpMatchResult"
     }).Events || [];

     var opponentMatch = opponentEvents.find(e => e.EventData.matchId === args.matchId);

     if (!opponentMatch) {
        // Opponent hasn’t reported yet, retry from client later
        return { success: false, message: "Verification pending — opponent not ready yet." };
     }

     // Otherwise, validate complementary results
     var isValid =
        (args.result === "win" && opponentMatch.EventData.result === "lose") ||
        (args.result === "lose" && opponentMatch.EventData.result === "win");

     if (!isValid) {
        return { success: false, message: "Verification failed — mismatched results." };
     }

     // Proceed to grant rewards if valid
    }


    // === STEP 4: Get and parse player data ===
    var userDataResult = server.GetUserData({ PlayFabId: playerId });
    var data = userDataResult.Data || {};
    var updatedPlayerData = {};

    if (data.playerData && data.playerData.Value) {
        try {
            updatedPlayerData = JSON.parse(data.playerData.Value);
        } catch (e) {
            updatedPlayerData = {};
        }
    }

    // === STEP 5: Compute rewards (only if verified or non-pvp) ===
    var reward = { xp: 0, currency: 0, ranking: 0 };
    if (verified) {
        var playerLevel = updatedPlayerData.level || 1;
        reward = computeReward(args.result, mode, isRanked, playerLevel);

        // === Grant currency ===
        if (reward.currency > 0) {
            server.AddUserVirtualCurrency({
                PlayFabId: playerId,
                VirtualCurrency: "LC",
                Amount: reward.currency
            });
        }

        // === Initialize data fields ===
        if (typeof updatedPlayerData.experiencePoints !== "number") updatedPlayerData.experiencePoints = 0;
        if (typeof updatedPlayerData.totalGames !== "number") updatedPlayerData.totalGames = 0;
        if (typeof updatedPlayerData.totalWins !== "number") updatedPlayerData.totalWins = 0;
        if (typeof updatedPlayerData.level !== "number") updatedPlayerData.level = 1;
        if (typeof updatedPlayerData.campaignLevel !== "number") updatedPlayerData.campaignLevel = 0;

        // === Apply progress ===
        updatedPlayerData.experiencePoints += Math.floor(reward.xp);
        updatedPlayerData.totalGames += 1;
        if (args.result === "win") updatedPlayerData.totalWins += 1;
        if (args.result === "win" && mode === "campaign") updatedPlayerData.campaignLevel += 1;

        // === Level-up check ===
        var currentLevel = updatedPlayerData.level;
        var currentXP = updatedPlayerData.experiencePoints;
        var shouldLevelUp = currentLevel >= 1 && currentXP >= currentLevel * 5000;
        if (shouldLevelUp) updatedPlayerData.level += 1;

        server.UpdateUserData({
            PlayFabId: playerId,
            Data: { playerData: JSON.stringify(updatedPlayerData) }
        });

        // === Ranking reward ===
        if (reward.ranking !== 0) {
            var stats = server.GetPlayerStatistics({ PlayFabId: playerId });
            var currentRanking = 0;
            for (var i = 0; i < stats.Statistics.length; i++) {
                if (stats.Statistics[i].StatisticName === "rankingScore") {
                    currentRanking = stats.Statistics[i].Value;
                    break;
                }
            }
            server.UpdatePlayerStatistics({
                PlayFabId: playerId,
                Statistics: [{
                    StatisticName: "rankingScore",
                    Value: currentRanking + reward.ranking
                }]
            });
        }
    } else {
        // If not verified, log a pending verification entry for follow-up
        server.WritePlayerEvent({
            PlayFabId: playerId,
            EventName: "pvpPendingVerification",
            Body: {
                matchId: matchId,
                opponentId: opponentId,
                result: args.result,
                isRanked: isRanked,
                timestamp: new Date().toISOString()
            }
        });
    }

    // === STEP 6: Return results ===
    var inventory = server.GetUserInventory({ PlayFabId: playerId });

    return {
        success: true,
        mode: mode,
        verified: verified,
        result: args.result,
        xpGranted: reward.xp,
        rankingScoreGranted: reward.ranking,
        currencyGranted: reward.currency,
        newBalance: inventory.VirtualCurrency["LC"],
        updatedPlayerData: updatedPlayerData,
        message: verified
            ? "Match verified and rewards granted."
            : "Match pending opponent confirmation."
    };
};


// === Helper Function ===
function computeReward(result, mode, isRanked, playerLvl) {
    var xp = 0, currency = 0, ranking = 0;

    if (result === "win") {
        xp = (mode === "pvp") ? 200 : (mode === "campaign" ? 250 : 150);
        currency = (mode === "pvp") ? 30 : (mode === "campaign" ? 20 : 15);
        ranking = isRanked ? 150 : 0;
    } else if (result === "lose") {
        xp = (mode === "pvp") ? 100 : (mode === "campaign" ? 75 : 50);
        currency = (mode === "pvp") ? 10 : (mode === "campaign" ? 5 : 0);
        ranking = isRanked ? -100 : 0;
    }
    if(playerLvl < 11) xp *= 10/playerLvl; 
    return { xp: xp, currency: currency, ranking: ranking };
}

handlers.verifyRecentPvPMatches = function (args, context) {
    var now = Date.now();
    var cutoffMinutes = args.cutoffMinutes || 5; // default grace period
    var cutoffTime = now - (cutoffMinutes * 60 * 1000);
    var verifiedCount = 0;
    var mismatchedCount = 0;
    var pendingCount = 0;

    log.info("=== Running PvP Match Verification ===");

    // Ideally this would come from a stored event log DB, but PlayFab’s built-in
    // event querying is limited — so in production, store events in title data or DataTables.
    // For now, simulate a sample event pool.
    var allEvents = getRecentPvPEvents(cutoffMinutes);

    // Group events by matchId
    var matchesById = {};
    for (var i = 0; i < allEvents.length; i++) {
        var ev = allEvents[i];
        var matchId = ev.Body.matchId;
        if (!matchId) continue;
        if (!matchesById[matchId]) matchesById[matchId] = [];
        matchesById[matchId].push(ev);
    }

    // Analyze grouped events
    var results = [];

    for (var id in matchesById) {
        var evs = matchesById[id];
        if (evs.length < 2) {
            // Only one player reported
            pendingCount++;
            results.push({
                matchId: id,
                status: "pending",
                players: evs.map(e => e.PlayFabId)
            });
            continue;
        }

        // Two or more reports found — check for complementary results
        var a = evs[0].Body.result;
        var b = evs[1].Body.result;
        var same = a === b;

        if (!same && ((a === "win" && b === "lose") || (a === "lose" && b === "win"))) {
            verifiedCount++;
            results.push({
                matchId: id,
                status: "verified",
                players: evs.map(e => e.PlayFabId)
            });

            // Optionally reward both verified players here if not already done
            log.info("✅ Verified match: " + id);
        } else {
            mismatchedCount++;
            results.push({
                matchId: id,
                status: "mismatch",
                players: evs.map(e => e.PlayFabId),
                results: [a, b]
            });
            log.info("⚠️ Mismatch in match: " + id);
        }
    }

    // Return summary
    return {
        verified: verifiedCount,
        mismatched: mismatchedCount,
        pending: pendingCount,
        results: results
    };
};


