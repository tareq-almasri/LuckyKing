handlers.buyPack = function (args, context) {
  var playerId = currentPlayerId;
  var storeId = args.storeId || "gems_store";
  var itemId = args.itemId;
  var catalogVersion = args.catalogVersion || "LuckyStore";
  var currency = args.currency || "LG";
  var expectedPrice = args.price; // client-provided, but we validate

  if (!itemId || !expectedPrice) {
    return { success: false, error: "missing_parameters" };
  }

  // 1. Get Store definition
  var storeResult = server.GetStoreItems({
    StoreId: storeId,
    CatalogVersion: catalogVersion,
  });

  var matchedItem = storeResult.Store.find((s) => s.ItemId === itemId);
  if (!matchedItem) {
    return { success: false, error: "item_not_in_store" };
  }

  var serverPrice = matchedItem.VirtualCurrencyPrices[currency];
  if (!serverPrice) {
    return { success: false, error: "item_not_sold_in_currency" };
  }

  if (serverPrice !== expectedPrice) {
    return { success: false, error: "price_mismatch" };
  }

  // 2. Subtract currency (server-side authority)
  server.SubtractUserVirtualCurrency({
    PlayFabId: playerId,
    VirtualCurrency: currency,
    Amount: serverPrice,
  });

  // 3. Grant item
  var grantResult = server.GrantItemsToUser({
    PlayFabId: playerId,
    ItemIds: [itemId],
    CatalogVersion: catalogVersion,
    Annotation: "Purchased from store: " + storeId,
  });

  return {
    success: true,
    grantedItems: grantResult.ItemGrantResults,
  };
};

